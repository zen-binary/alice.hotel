CREATE TABLE IF NOT EXISTS SYS_ROLE (
  RL_ID BIGINT NOT NULL PRIMARY KEY,
  RL_NM VARCHAR(100) NULL,
  CATEGORY VARCHAR(50) NULL,
  ETC VARCHAR(200) NULL,
  REG_ID VARCHAR(50) NULL,
  REG_DATE DATETIME NULL,
  MODIFY_ID VARCHAR(50) NULL,
  MODIFY_DATE DATETIME NULL,
  RL_CD VARCHAR(50) NULL,
  RL_DESC VARCHAR(200) NULL
);

CREATE TABLE IF NOT EXISTS MENU (
  ID BIGINT NOT NULL PRIMARY KEY AUTO_INCREMENT,
  SITE_TYPE VARCHAR(20) NULL,
  NAME VARCHAR(200) NOT NULL,
  ROUTE VARCHAR(200) NULL,
  PARENT_ID BIGINT NULL,
  SUB_URL VARCHAR(200) NULL,
  DISPLAY_ORDER VARCHAR(20) NULL,
  DELETE_FLAG VARCHAR(1) NOT NULL DEFAULT 'N',
  DEL_YN VARCHAR(1) NOT NULL DEFAULT 'N',
  VN_NAME VARCHAR(200) NULL,
  SCREEN_NAME VARCHAR(100) NULL,
  BLANK_SCREEN VARCHAR(10) NULL,
  REG_ID VARCHAR(50) NULL,
  REG_DATE DATETIME NULL DEFAULT CURRENT_TIMESTAMP,
  MODIFY_ID VARCHAR(50) NULL,
  MODIFY_DATE DATETIME NULL
);

CREATE TABLE IF NOT EXISTS MENU_ROLE (
  MENU_ID BIGINT NOT NULL,
  ROLE_ID BIGINT NOT NULL,
  PRIMARY KEY (MENU_ID, ROLE_ID)
);

