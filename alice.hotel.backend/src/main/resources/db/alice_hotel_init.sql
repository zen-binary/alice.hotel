-- Alice Hotel Booking — base schema + demo data
CREATE DATABASE IF NOT EXISTS alice_hotel CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE alice_hotel;

CREATE TABLE IF NOT EXISTS CPS_USER (
  USER_ID   VARCHAR(50)  NOT NULL PRIMARY KEY,
  USER_PW   VARCHAR(200) NOT NULL,
  USER_NO   VARCHAR(50)  NULL,
  USER_NAME VARCHAR(100) NOT NULL,
  USER_DIV  VARCHAR(20)  NOT NULL DEFAULT 'ADM',
  DIVISION  VARCHAR(50)  NULL
);

CREATE TABLE IF NOT EXISTS SYS_USER_ROLE (
  UR_ID  BIGINT AUTO_INCREMENT PRIMARY KEY,
  RL_ID  VARCHAR(20) NOT NULL,
  USER_ID VARCHAR(50) NOT NULL,
  USE_YN VARCHAR(1)  NOT NULL DEFAULT 'Y',
  PUBLIC_INFO VARCHAR(1) NULL
);

CREATE TABLE IF NOT EXISTS SYS_LOGIN_HISTORY (
  LH_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
  USER_ID VARCHAR(50) NOT NULL,
  REG_DATE DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS CPS_MENU_CONN_HIS (
  MENU_CONN_HIS_ID VARCHAR(40) NOT NULL PRIMARY KEY,
  CONN_ID VARCHAR(50) NULL,
  CONN_URL VARCHAR(300) NULL,
  CONN_IP VARCHAR(50) NULL,
  CONN_DATE DATETIME NULL
);

CREATE TABLE IF NOT EXISTS CMMN_CODE_MNG (
  CD_ID VARCHAR(50) NOT NULL PRIMARY KEY,
  UP_CD_ID VARCHAR(50) NULL,
  CD_CATEGORY VARCHAR(50) NULL,
  CD_NM VARCHAR(200) NULL,
  ORD_NO BIGINT NULL
);

CREATE TABLE IF NOT EXISTS FILE_MNG (
  FIM_ID VARCHAR(50) NOT NULL PRIMARY KEY,
  FIM_SUB_FILE_ID VARCHAR(50) NULL,
  FIM_FILE_CATEGORY VARCHAR(50) NULL,
  FIM_FILE_NAME VARCHAR(255) NULL,
  FIM_FILE_PATH VARCHAR(500) NULL,
  FIM_FILE_EXT VARCHAR(20) NULL,
  FIM_FILE_SIZE BIGINT NULL,
  FIM_USE_YN VARCHAR(1) NULL,
  FIM_REFER_KEY_ID VARCHAR(100) NULL,
  FIM_FILE_ORG_NAME VARCHAR(255) NULL,
  FIM_SECTION_NAME VARCHAR(100) NULL,
  DEL_YN VARCHAR(1) NULL,
  REG_ID VARCHAR(50) NULL,
  REG_DATE DATETIME(6) NULL,
  MODIFY_ID VARCHAR(50) NULL,
  MODIFY_DATE DATETIME(6) NULL,
  KEY idx_file_refer (FIM_REFER_KEY_ID, FIM_FILE_CATEGORY, FIM_SECTION_NAME)
);

CREATE TABLE IF NOT EXISTS sys_resource (
  rs_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  url VARCHAR(500) NULL,
  http_method VARCHAR(20) NULL,
  rs_nm VARCHAR(200) NULL,
  rs_type VARCHAR(50) NULL,
  reg_date DATETIME NULL
);

CREATE TABLE IF NOT EXISTS sys_resource_role (
  rr_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  rs_id BIGINT NOT NULL,
  rl_id BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS hotel_room (
  room_id     VARCHAR(40)  NOT NULL PRIMARY KEY,
  room_code   VARCHAR(50)  NOT NULL,
  room_name   VARCHAR(200) NOT NULL,
  room_type   VARCHAR(50)  NOT NULL,
  price       DECIMAL(12,2) NOT NULL DEFAULT 0,
  capacity    INT NOT NULL DEFAULT 2,
  status      VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
  description VARCHAR(1000) NULL,
  del_yn      VARCHAR(1) NOT NULL DEFAULT 'N',
  reg_id      VARCHAR(50) NULL,
  reg_date    DATETIME NULL,
  mod_id      VARCHAR(50) NULL,
  mod_date    DATETIME NULL,
  UNIQUE KEY uk_hotel_room_code (room_code)
);

